-- Physical pallet slots for the 6 warehouses with CAD floor plans
-- (KHOTP, KHOTD1, KHOTD2, HD1, HD2, KHOPL). Identity only — geometry lives in
-- frontend/src/constants/warehouseLayouts.ts.
-- Slot ids are deterministic ('WS-<maKho>-<zone>-<code>') so seeding is stable and
-- idempotent; deliberate deviation from the CUID convention.

-- CreateTable
CREATE TABLE "business"."warehouse_slots" (
    "id" TEXT NOT NULL,
    "warehouseId" TEXT NOT NULL,
    "zone" TEXT NOT NULL,
    "code" TEXT NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "warehouse_slots_pkey" PRIMARY KEY ("id")
);

-- AlterTable
ALTER TABLE "business"."lot_products" ADD COLUMN "slotId" TEXT;

-- CreateIndex
CREATE UNIQUE INDEX "warehouse_slots_warehouseId_zone_code_key" ON "business"."warehouse_slots"("warehouseId", "zone", "code");

-- AddForeignKey
ALTER TABLE "business"."warehouse_slots" ADD CONSTRAINT "warehouse_slots_warehouseId_fkey" FOREIGN KEY ("warehouseId") REFERENCES "business"."warehouses"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "business"."lot_products" ADD CONSTRAINT "lot_products_slotId_fkey" FOREIGN KEY ("slotId") REFERENCES "business"."warehouse_slots"("id") ON DELETE SET NULL ON UPDATE CASCADE;

